#!/usr/bin/env node
'use strict';

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repositoryRoot = path.join(__dirname, '..');
const generatedDirectory = path.join(repositoryRoot, 'src', 'generated');
const generatedPath = path.join(generatedDirectory, 'build-provenance.ts');
const requireClean = process.argv.includes('--require-clean');

class BuildProvenanceError extends Error {
  constructor(message) {
    super(message);
    this.name = 'BuildProvenanceError';
  }
}

function readGit(args) {
  return execFileSync('git', args, {
    cwd: repositoryRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

const packageJson = JSON.parse(
  fs.readFileSync(path.join(repositoryRoot, 'package.json'), 'utf8')
);
if (typeof packageJson.version !== 'string' || packageJson.version.trim().length === 0) {
  throw new BuildProvenanceError(
    'package.json.version must be a non-empty string for build provenance'
  );
}

const commit = readGit(['rev-parse', '--verify', 'HEAD']);
if (!/^[a-f0-9]{40,64}$/.test(commit)) {
  throw new BuildProvenanceError(`git HEAD is not a full lowercase commit id: ${commit}`);
}
if (requireClean) {
  const dirty = readGit(['status', '--porcelain=v1', '--untracked-files=no']);
  if (dirty.length > 0) {
    throw new BuildProvenanceError('refusing to build provenance from tracked dirty source');
  }
}

const provenance = {
  version: packageJson.version,
  commit,
  built_at: new Date().toISOString(),
};
const content = `// Generated by scripts/generate-build-provenance.js. Do not edit.\nexport const BUILD_PROVENANCE = Object.freeze(${JSON.stringify(provenance)}) as Readonly<{ version: string; commit: string; built_at: string }>;\n`;

fs.mkdirSync(generatedDirectory, { recursive: true });
const candidatePath = `${generatedPath}.${process.pid}.candidate`;
fs.writeFileSync(candidatePath, content, { encoding: 'utf8', mode: 0o600, flag: 'wx' });
fs.renameSync(candidatePath, generatedPath);
